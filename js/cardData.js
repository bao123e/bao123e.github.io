class CardDataService {
  constructor() {
    this.currentBanner = 'yugioh'; // 'yugioh' | 'pokemon' | 'wuwa'
    this.pools = {
      yugioh: [],
      pokemon: [],
      wuwa: WUWA_RESONATORS,
      fallback: FALLBACK_CARDS
    };
    this.isLoading = false;
    this.artCache = new Map();

    // Generate fallback artworks upfront so they are instant data URLs
    this.initFallbackArtworks();
  }

  // Pre-generate procedural art for all fallback cards
  initFallbackArtworks() {
    this.pools.fallback.forEach(card => {
      if (!card.image) {
        card.image = this.generateProceduralArt(card);
      }
    });
  }

  // Generate high-resolution procedural canvas artwork for any card
  generateProceduralArt(card) {
    if (this.artCache.has(card.id)) {
      return this.artCache.get(card.id);
    }

    const canvas = document.createElement('canvas');
    canvas.width = 420;
    canvas.height = 600;
    const ctx = canvas.getContext('2d');

    // Deep cosmic background gradient
    const bgGrad = ctx.createLinearGradient(0, 0, 0, 600);
    const p = card.palette || ["#0b0d19", "#1e1b4b", "#4338ca", "#38bdf8", "#ffffff"];
    bgGrad.addColorStop(0, p[0]);
    bgGrad.addColorStop(0.5, p[1]);
    bgGrad.addColorStop(1, p[2] || p[0]);
    ctx.fillStyle = bgGrad;
    ctx.fillRect(0, 0, 420, 600);

    // Nebula dust swirls
    for (let i = 0; i < 4; i++) {
      const radGrad = ctx.createRadialGradient(
        100 + i * 80, 150 + i * 90, 20,
        150 + i * 60, 200 + i * 70, 220
      );
      radGrad.addColorStop(0, (p[3] || "#ec4899") + "55");
      radGrad.addColorStop(0.6, (p[2] || "#8b5cf6") + "22");
      radGrad.addColorStop(1, "transparent");
      ctx.fillStyle = radGrad;
      ctx.beginPath();
      ctx.arc(150 + i * 60, 200 + i * 70, 220, 0, Math.PI * 2);
      ctx.fill();
    }

    // Sacred geometric celestial circles & runes
    ctx.save();
    ctx.translate(210, 260);
    ctx.strokeStyle = (p[4] || "#ffffff") + "44";
    ctx.lineWidth = 1.5;

    // Rings
    ctx.beginPath();
    ctx.arc(0, 0, 130, 0, Math.PI * 2);
    ctx.stroke();

    ctx.beginPath();
    ctx.arc(0, 0, 95, 0, Math.PI * 2);
    ctx.setLineDash([8, 6]);
    ctx.stroke();
    ctx.setLineDash([]);

    // Astral Star Polygons
    const points = card.rarity === 'UR' ? 8 : (card.rarity === 'SSR' ? 6 : 5);
    ctx.strokeStyle = card.themeColor || "#38bdf8";
    ctx.lineWidth = 2;
    ctx.beginPath();
    for (let k = 0; k < points * 2; k++) {
      const radius = k % 2 === 0 ? 80 : 35;
      const angle = (k * Math.PI) / points;
      const x = Math.cos(angle) * radius;
      const y = Math.sin(angle) * radius;
      if (k === 0) ctx.moveTo(x, y);
      else ctx.lineTo(x, y);
    }
    ctx.closePath();
    ctx.stroke();

    // Central Core Pulse
    const coreGrad = ctx.createRadialGradient(0, 0, 5, 0, 0, 50);
    coreGrad.addColorStop(0, '#ffffff');
    coreGrad.addColorStop(0.4, card.themeColor || '#38bdf8');
    coreGrad.addColorStop(1, 'transparent');
    ctx.fillStyle = coreGrad;
    ctx.beginPath();
    ctx.arc(0, 0, 50, 0, Math.PI * 2);
    ctx.fill();

    ctx.restore();

    // Decorative Borders
    ctx.strokeStyle = (card.themeColor || '#38bdf8') + '88';
    ctx.lineWidth = 4;
    ctx.strokeRect(16, 16, 388, 568);

    // Corner Ornaments
    ctx.fillStyle = card.themeColor || '#38bdf8';
    [[20, 20], [400, 20], [20, 580], [400, 580]].forEach(([cx, cy]) => {
      ctx.beginPath();
      ctx.arc(cx, cy, 6, 0, Math.PI * 2);
      ctx.fill();
    });

    const dataUrl = canvas.toDataURL('image/png');
    this.artCache.set(card.id, dataUrl);
    return dataUrl;
  }

  // Load Yu-Gi-Oh! API Pool
  async loadYugiohPool() {
    if (this.pools.yugioh.length > 0) return this.pools.yugioh;
    try {
      this.isLoading = true;
      const url = 'https://db.ygoprodeck.com/api/v7/cardinfo.php?num=100&offset=0&sort=new';
      const controller = new AbortController();
      const timeoutId = setTimeout(() => controller.abort(), 7000);

      const resp = await fetch(url, { signal: controller.signal });
      clearTimeout(timeoutId);

      if (!resp.ok) throw new Error(`HTTP Error ${resp.status}`);
      const json = await resp.json();
      const rawCards = json.data || [];

      this.pools.yugioh = rawCards.map(c => {
        const atk = c.atk !== undefined && c.atk !== null ? Number(c.atk) : 1500;
        const def = c.def !== undefined && c.def !== null ? Number(c.def) : 1200;

        // Rarity mapping
        let rarity = 'R';
        let rarityName = 'Rare';
        let foilType = 'astral-cyan';
        let themeColor = '#38bdf8';

        if (atk >= 3000 || (c.type && c.type.includes('Link-5'))) {
          rarity = 'UR';
          rarityName = 'Ultra Rare';
          foilType = 'cosmic-rainbow';
          themeColor = '#f43f5e';
        } else if (atk >= 2500) {
          rarity = 'SSR';
          rarityName = 'Super Special Rare';
          foilType = 'solar-gold';
          themeColor = '#eab308';
        } else if (atk >= 1800) {
          rarity = 'SR';
          rarityName = 'Super Rare';
          foilType = 'void-purple';
          themeColor = '#a855f7';
        }

        const hasImgs = c.card_images && c.card_images[0];
        const imgUrl = hasImgs ? (c.card_images[0].image_url || c.card_images[0].image_url_small) : null;

        return {
          id: `ygo-${c.id}`,
          name: c.name,
          source: 'yugioh',
          type: (c.race || 'Warrior') + ' / ' + (c.type || 'Monster'),
          atk: atk,
          def: def,
          hp: Math.round(atk / 10),
          rarity: rarity,
          rarityName: rarityName,
          foilType: foilType,
          description: c.desc || 'A legendary creature summoned from the depths of the Astral Archive.',
          image: imgUrl,
          fullImage: imgUrl,
          themeColor: themeColor
        };
      });

      console.log(`[CardDataService] Successfully loaded ${this.pools.yugioh.length} Yu-Gi-Oh! cards.`);
      return this.pools.yugioh;
    } catch (err) {
      console.warn('[CardDataService] YGO API fetch failed or timed out. Using fallback pool.', err);
      return this.pools.fallback;
    } finally {
      this.isLoading = false;
    }
  }

  // Load Pokémon TCGdex API Pool
  async loadPokemonPool() {
    if (this.pools.pokemon.length > 0) return this.pools.pokemon;
    try {
      this.isLoading = true;
      const url = 'https://api.tcgdex.net/v2/en/sets/swsh3';
      const controller = new AbortController();
      const timeoutId = setTimeout(() => controller.abort(), 7000);

      const resp = await fetch(url, { signal: controller.signal });
      clearTimeout(timeoutId);

      if (!resp.ok) throw new Error(`HTTP Error ${resp.status}`);
      const json = await resp.json();
      const rawCards = json.cards || [];

      // Filter cards that have images
      const withImages = rawCards.filter(c => c.image);

      this.pools.pokemon = withImages.map((c, idx) => {
        // Deterministic mock/derived stats for Pokémon cards based on localId / index
        const hpBase = 100 + ((idx * 37) % 240); // 100 to 340
        const atkVal = hpBase * 10;
        const defVal = Math.round(atkVal * 0.85);

        let rarity = 'R';
        let rarityName = 'Rare';
        let foilType = 'astral-cyan';
        let themeColor = '#38bdf8';

        if (hpBase >= 300 || c.name.includes('VMAX') || c.name.includes('VSTAR')) {
          rarity = 'UR';
          rarityName = 'Ultra Rare';
          foilType = 'cosmic-rainbow';
          themeColor = '#f43f5e';
        } else if (hpBase >= 230 || c.name.includes(' V')) {
          rarity = 'SSR';
          rarityName = 'Super Special Rare';
          foilType = 'solar-gold';
          themeColor = '#eab308';
        } else if (hpBase >= 160) {
          rarity = 'SR';
          rarityName = 'Super Rare';
          foilType = 'void-purple';
          themeColor = '#a855f7';
        }

        const highImg = `${c.image}/high.webp`;

        return {
          id: `pkmn-${c.id}`,
          name: c.name,
          source: 'pokemon',
          type: 'Pokémon / Darkness Ablaze',
          atk: atkVal,
          def: defVal,
          hp: hpBase,
          rarity: rarity,
          rarityName: rarityName,
          foilType: foilType,
          description: `A powerful companion from the Darkness Ablaze galaxy. Local ID: #${c.localId}.`,
          image: highImg,
          themeColor: themeColor
        };
      });

      console.log(`[CardDataService] Successfully loaded ${this.pools.pokemon.length} Pokémon cards.`);
      return this.pools.pokemon;
    } catch (err) {
      console.warn('[CardDataService] Pokémon API fetch failed or timed out. Using fallback pool.', err);
      return this.pools.fallback;
    } finally {
      this.isLoading = false;
    }
  }

  // Get active pool cards
  async getCardsForBanner(bannerKey) {
    this.currentBanner = bannerKey;
    if (bannerKey === 'wuwa') {
      return this.pools.wuwa && this.pools.wuwa.length ? this.pools.wuwa : this.pools.fallback;
    } else if (bannerKey === 'yugioh') {
      const cards = await this.loadYugiohPool();
      return cards && cards.length ? cards : this.pools.fallback;
    } else if (bannerKey === 'pokemon') {
      const cards = await this.loadPokemonPool();
      return cards && cards.length ? cards : this.pools.fallback;
    }
    return this.pools.fallback;
  }

  // Get single card by ID across all pools
  getCardById(id) {
    const all = [
      ...this.pools.fallback,
      ...(this.pools.wuwa || []),
      ...(this.pools.yugioh || []),
      ...(this.pools.pokemon || [])
    ];
    return all.find(c => c.id === id) || null;
  }

  // Graceful multi-stage image error handler
  handleImageError(imgEl, cardId) {
    if (!imgEl) return;
    let card = this.getCardById(cardId);

    // If card has a full alternative image and we haven't tried it yet
    if (card && card.fullImage && imgEl.src !== card.fullImage) {
      imgEl.onerror = () => {
        imgEl.onerror = null;
        imgEl.src = this.generateProceduralArt(card);
      };
      imgEl.src = card.fullImage;
      return;
    }

    imgEl.onerror = null;
    if (!card) {
      card = {
        id: cardId || 'fallback',
        name: 'Astral Entity',
        rarity: 'R',
        themeColor: '#38bdf8'
      };
    }
    imgEl.src = this.generateProceduralArt(card);
  }
}

// Global service instance
window.cardDataService = new CardDataService();
